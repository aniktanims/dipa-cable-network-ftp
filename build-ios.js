// Builds ios/Movie Fetcher.js: a single Scriptable (https://scriptable.app) script that runs
// the whole app on an iPhone with no PC. Run with: node build-ios.js
const fs = require('fs');
const path = require('path');

const read = f => fs.readFileSync(path.join(__dirname, f), 'utf8');
const html = read('index.html');

// Page side of the bridge. The page queues requests; the Scriptable side picks them up with a
// quick evaluateJavaScript call every few milliseconds, does them natively and hands back results.
// Errors are shown on screen, since there's no developer console on the phone.
const bridge = `
window.MF_PLAYER_ONLY = __MF_PLAYER__;
window.__mfShowError = msg => {
    let box = document.getElementById('mf-errors');
    if (!box) {
        box = document.createElement('pre');
        box.id = 'mf-errors';
        box.style.cssText = 'position:fixed;left:8px;right:8px;bottom:8px;z-index:9999;background:#b00020;color:#fff;'
            + 'padding:10px;border-radius:8px;font:12px/1.4 monospace;white-space:pre-wrap;max-height:40vh;overflow:auto';
        (document.body || document.documentElement).appendChild(box);
    }
    box.textContent += msg + String.fromCharCode(10);
};
window.addEventListener('error', e => __mfShowError('Error: ' + e.message + (e.lineno ? ' (line ' + e.lineno + ')' : '')));
window.addEventListener('unhandledrejection', e => __mfShowError('Error: ' + ((e.reason && e.reason.message) || e.reason)));
window.MFNative = (() => {
    let seq = 0, queue = [];
    const pending = new Map();
    function call(type, args) {
        return new Promise((resolve, reject) => {
            const id = ++seq;
            pending.set(id, { resolve, reject });
            queue.push(Object.assign({ id, type }, args));
        });
    }
    function fire(type, args) {
        queue.push(Object.assign({ id: 0, type }, args));
    }
    // Called by the Scriptable side: delivers finished results, returns the new requests.
    window.__mfNext = results => {
        for (const r of results) {
            const p = pending.get(r.id);
            if (!p) continue;
            pending.delete(r.id);
            r.ok ? p.resolve(r.value) : p.reject(new Error(r.error));
        }
        return queue.splice(0);
    };
    return {
        store: __MF_STORE__,
        post: (url, body) => call('post', { url, body }),
        get: (url, headers) => call('get', { url, headers }),
        open: url => fire('open', { url }),
        copy: text => fire('copy', { text }),
        save: (key, value) => fire('save', { key, value }),
        play: media => fire('play', { media })
    };
})();
`;

// The iPhone page has no server to load files from, so the logo goes in as a data URL.
const logo = 'data:image/png;base64,' + fs.readFileSync(path.join(__dirname, 'assets', 'logo.png')).toString('base64');
let page = html.split('src="assets/logo.png"').join(`src="${logo}"`);
for (const [tag, file, before] of [
    ['<script src="core.js"></script>', 'core.js', `<script>${bridge}</script>\n`],
    ['<script src="mkv.js"></script>', 'mkv.js', ''],
    ['<script src="player-ui.js"></script>', 'player-ui.js', '']
]) {
    if (!page.includes(tag)) throw new Error('index.html is missing ' + tag);
    const code = read(file);
    page = page.replace(tag, () => `${before}<script>${code}</script>`);
}

const runner = `// Variables used by Scriptable.
// These must be at the very top of the file. Do not edit.
// icon-color: red; icon-glyph: film;

// Dipa Cable Network FTP for iPhone (DHAKA FLIX Movie Fetcher for iPhone) by Mostofa Tanim Anik.
// Generated by build-ios.js - edit index.html / core.js instead.
// Needs the free Scriptable app and a connection that can reach the DHAKA FLIX servers (172.16.50.x).

const PAGE = ${JSON.stringify(page)};

const fm = FileManager.local();
const dataPath = fm.joinPath(fm.documentsDirectory(), 'movie-fetcher-data.json');
let data = {};
try {
    if (fm.fileExists(dataPath)) data = JSON.parse(fm.readString(dataPath));
} catch (e) { /* start fresh if the saved file is damaged */ }
let dirty = false;

function pageHtml(player) {
    const json = v => JSON.stringify(v).replace(/</g, '\\\\u003c');
    return PAGE.replace('__MF_STORE__', () => json(data)).replace('__MF_PLAYER__', () => json(player || null));
}

async function handle(req) {
    switch (req.type) {
        case 'post': {
            const r = new Request(req.url);
            r.method = 'POST';
            r.headers = { 'Content-Type': 'application/json' };
            r.body = JSON.stringify(req.body);
            r.timeoutInterval = 30;
            return r.loadJSON();
        }
        case 'get': {
            const r = new Request(req.url);
            r.headers = req.headers || {};
            r.timeoutInterval = 20;
            const json = await r.loadJSON();
            if (r.response && r.response.statusCode >= 400) throw new Error('HTTP ' + r.response.statusCode);
            return json;
        }
        case 'open':
            Safari.open(req.url);
            return null;
        case 'copy':
            Pasteboard.copy(req.text);
            return null;
        case 'save':
            data[req.key] = req.value;
            dirty = true;
            return null;
        case 'play':
            openPlayer(req.media);
            return null;
    }
    throw new Error('Unknown request ' + req.type);
}

function saveData() {
    if (!dirty) return;
    dirty = false;
    fm.writeString(dataPath, JSON.stringify(data));
}

// Serve one web view's requests until it is closed.
const sleep = ms => new Promise(resolve => Timer.schedule(ms, false, resolve));

async function serve(web, presented, name) {
    let closed = false;
    presented.then(() => { closed = true; saveData(); });
    const ready = [];
    let inflight = 0, errors = 0;
    while (!closed) {
        let batch;
        try {
            batch = await web.evaluateJavaScript('__mfNext(' + JSON.stringify(ready.splice(0)) + ')');
            errors = 0;
        } catch (e) {
            // The page may still be starting; give up only if it keeps failing.
            if (++errors === 1 || errors % 50 === 0) console.log(name + ' bridge: ' + e);
            if (errors > 600) break;
            await sleep(100);
            continue;
        }
        for (const req of batch || []) {
            inflight++;
            handle(req)
                .then(value => ({ id: req.id, ok: true, value }))
                .catch(err => ({ id: req.id, ok: false, error: String((err && err.message) || err) }))
                .then(result => {
                    inflight--;
                    if (req.id) ready.push(result);
                });
        }
        saveData();
        if (!(batch && batch.length) && !ready.length) await sleep(inflight ? 30 : 80);
    }
}

// The player gets its own view whose address is the movie server's, so the page may read the
// file directly (needed to stream MKV in the browser).
async function openPlayer(media) {
    const file = media.playlist[media.index] || media.playlist[0];
    const origin = file.url.match(/^https?:\\/\\/[^/]+\\//)[0];
    const web = new WebView();
    await web.loadHTML(pageHtml(media), origin);
    serve(web, web.present(true), 'player');
}

try {
    console.log('Movie Fetcher: loading page (' + Math.round(PAGE.length / 1024) + ' KB)');
    const main = new WebView();
    await main.loadHTML(pageHtml(null));
    console.log('Movie Fetcher: page loaded');
    const mainClosed = main.present(true);
    mainClosed.then(() => { saveData(); Script.complete(); });
    await serve(main, mainClosed, 'main');
} catch (e) {
    console.error('Movie Fetcher failed: ' + e);
    const a = new Alert();
    a.title = 'Movie Fetcher';
    a.message = String(e);
    a.addAction('OK');
    await a.present();
}
`;

fs.mkdirSync(path.join(__dirname, 'ios'), { recursive: true });
const out = path.join(__dirname, 'ios', 'Movie Fetcher.js');
fs.writeFileSync(out, runner);
console.log(`Wrote ${out} (${Math.round(runner.length / 1024)} KB)`);
